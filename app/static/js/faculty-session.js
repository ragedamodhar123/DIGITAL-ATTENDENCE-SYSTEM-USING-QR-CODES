// Live attendance screen: shows the rotating QR code and the counts.
//
// - Asks the server every 2 s, and right after each 10 s code change, so a new
//   code appears within a fraction of a second.
// - The countdown bar uses the server's timing, not the laptop clock.
// - If the connection drops, a banner appears and retries slow down a little.
//   If no fresh code arrives before the shown code would expire, the code is
//   blurred out: students should never scan a code that will be rejected.
// - Keeps the screen awake while attendance runs (where the browser allows).
(function () {
  "use strict";

  var root = document.getElementById("live-session");
  if (!root || !window.AttendanceApi) return;

  var POLL_MS = 2000;
  var MAX_BACKOFF_MS = 5000;

  var liveUrl = root.getAttribute("data-live-url");
  var graceWindows = parseInt(root.getAttribute("data-grace-windows"), 10) || 1;
  var box = root.querySelector(".qr-box");
  var codeHolder = root.querySelector(".qr-code");
  var overlay = root.querySelector(".qr-overlay");
  var timerBar = root.querySelector(".qr-timer-bar");
  var banner = root.querySelector(".connection-banner");
  var fields = {};
  ["present", "not_yet", "expected", "ends_at"].forEach(function (name) {
    fields[name] = root.querySelector('[data-field="' + name + '"]');
  });
  var recentList = document.querySelector('[data-field="recent"]');

  var currentSvg = "";
  var codeValidUntil = 0;   // performance.now() time after which the shown code is expired
  var failures = 0;
  var stopped = false;
  var pollTimer = null;
  var wakeLock = null;

  function now() { return (window.performance && performance.now) ? performance.now() : Date.now(); }

  function setState(state, text) {
    box.setAttribute("data-state", state);
    overlay.textContent = text || "";
  }

  function setText(element, value) {
    if (element && element.textContent !== String(value)) element.textContent = value;
  }

  function renderRecent(recent) {
    if (!recentList) return;
    recentList.textContent = "";
    if (!recent || !recent.length) {
      var empty = document.createElement("li");
      empty.className = "text-muted";
      empty.textContent = "Nobody yet.";
      recentList.appendChild(empty);
      return;
    }
    recent.forEach(function (item) {
      var li = document.createElement("li");
      li.textContent = item.at + "  " + item.name + " (" + item.username + ")";  // textContent: names never become HTML
      recentList.appendChild(li);
    });
  }

  function restartTimerBar(msLeft, rotationMs) {
    if (!timerBar) return;
    var fraction = Math.max(0, Math.min(1, msLeft / rotationMs));
    timerBar.style.transition = "none";
    timerBar.style.width = (fraction * 100) + "%";
    void timerBar.offsetWidth; // apply the reset before animating
    timerBar.style.transition = "width " + msLeft + "ms linear";
    timerBar.style.width = "0%";
  }

  function schedule(delayMs) {
    if (stopped) return;
    clearTimeout(pollTimer);
    pollTimer = setTimeout(poll, delayMs);
  }

  function checkStale() {
    if (currentSvg && now() > codeValidUntil) {
      setState("stale", "Code out of date. Reconnecting...");
    }
  }

  function handleSuccess(data) {
    failures = 0;
    banner.classList.add("d-none");

    if (data.counts) {
      setText(fields.present, data.counts.present);
      setText(fields.not_yet, data.counts.not_yet);
      setText(fields.expected, data.counts.expected);
    }
    if (data.ends_at) setText(fields.ends_at, data.ends_at);
    renderRecent(data.recent);

    if (data.status !== "open" || !data.qr) {
      // Stopped by a co-teacher, or closed automatically: show the final summary.
      stopped = true;
      setState("closed", "Attendance has ended.");
      window.location.reload();
      return;
    }

    var qr = data.qr;
    if (qr.svg !== currentSvg) {
      // The SVG is generated by our own server from a code, never from user input.
      codeHolder.innerHTML = qr.svg;
      currentSvg = qr.svg;
    }
    // A code stays valid for its own window plus the grace windows after it.
    codeValidUntil = now() + qr.refresh_in_ms + graceWindows * qr.rotation_ms;
    setState("live", "");
    restartTimerBar(qr.refresh_in_ms, qr.rotation_ms);

    // Poll again just after the code changes (or sooner, for the counts).
    schedule(Math.min(POLL_MS, qr.refresh_in_ms + 150));
  }

  function handleFailure(result) {
    if (result.status === 401) { window.location.reload(); return; }       // logged out: the server redirects
    if (result.status === 403 || result.status === 404) {
      stopped = true;
      setState("stale", "This attendance screen is no longer available.");
      return;
    }
    failures += 1;
    banner.classList.remove("d-none");
    checkStale();
    schedule(Math.min(POLL_MS * Math.pow(1.5, failures - 1), MAX_BACKOFF_MS));
  }

  function poll() {
    if (stopped) return;
    window.AttendanceApi.getJSON(liveUrl, { timeoutMs: 8000 }).then(function (result) {
      if (stopped) return;
      if (result.ok) handleSuccess(result.data); else handleFailure(result);
    });
  }

  // Blur the code the moment it expires if no newer one has arrived.
  setInterval(checkStale, 500);

  // ---- full screen (for projectors) and keeping the screen awake -------------

  var fullscreenButton = root.querySelector('[data-action="fullscreen"]');
  if (fullscreenButton) {
    if (!root.requestFullscreen) {
      fullscreenButton.classList.add("d-none");
    } else {
      fullscreenButton.addEventListener("click", function () {
        if (document.fullscreenElement) document.exitFullscreen(); else root.requestFullscreen();
      });
    }
  }

  function keepAwake() {
    if (!navigator.wakeLock || document.hidden) return;
    navigator.wakeLock.request("screen").then(function (lock) { wakeLock = lock; }, function () { /* not allowed: ignore */ });
  }
  document.addEventListener("visibilitychange", function () {
    if (!document.hidden) {
      keepAwake();      // the browser drops the wake lock when the tab is hidden
      schedule(0);      // and refresh at once when the faculty comes back
    }
  });

  keepAwake();
  poll();
})();